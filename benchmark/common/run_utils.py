"""Shared utilities for the benchmark harness.

Every track writes its runs to a directory created by `make_run_dir`. The
directory name encodes the timestamp, tool, and run number so artifacts are
sortable and self-describing.

Manifest contract
-----------------
Every run directory contains `manifest.json` with at minimum:
    track             "track-a" or "track-b"
    tool              "janissary", "zap", "nuclei"
    tool_version      string as reported by the tool
    run_number        1, 2, 3
    target_version    commit hash or image tag of the target
    harness_commit    git HEAD of the harness repo at run time
    started_at        ISO-8601 UTC
    finished_at       ISO-8601 UTC (written by finalize_manifest)
    exit_code         subprocess exit code (written by finalize_manifest)
    invocation        list of args as invoked

Do not edit this file to change results. Only run artifact JSON is
authoritative; the harness code is a fixed part of the pre-registration.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from collections.abc import Iterable, Sequence
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

BENCH_ROOT = Path(__file__).resolve().parent.parent


def iso_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def harness_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=BENCH_ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()
    except Exception:
        return "unknown"


def make_run_dir(track: str, tool: str, run_number: int) -> Path:
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    name = f"{ts}-{tool}-r{run_number}"
    path = BENCH_ROOT / track / "runs" / name
    path.mkdir(parents=True, exist_ok=False)
    return path


def write_manifest(run_dir: Path, **fields: Any) -> Path:
    doc = {
        "track": fields.pop("track", None),
        "tool": fields.pop("tool", None),
        "tool_version": fields.pop("tool_version", "unknown"),
        "run_number": fields.pop("run_number", None),
        "target_version": fields.pop("target_version", "unknown"),
        "harness_commit": harness_commit(),
        "started_at": fields.pop("started_at", iso_now()),
        **fields,
    }
    path = run_dir / "manifest.json"
    path.write_text(json.dumps(doc, indent=2, sort_keys=True), encoding="utf-8")
    return path


def finalize_manifest(
    run_dir: Path,
    exit_code: int,
    tool_version: str | None = None,
) -> None:
    path = run_dir / "manifest.json"
    doc = json.loads(path.read_text(encoding="utf-8"))
    doc["finished_at"] = iso_now()
    doc["exit_code"] = exit_code
    if tool_version is not None:
        doc["tool_version"] = tool_version
    path.write_text(json.dumps(doc, indent=2, sort_keys=True), encoding="utf-8")


def run_subprocess(
    cmd: Sequence[str],
    run_dir: Path,
    *,
    timeout: float | None = None,
    env: dict[str, str] | None = None,
) -> int:
    """Run `cmd`, capture stdout/stderr into run_dir, return exit code."""
    stdout_path = run_dir / "stdout.log"
    stderr_path = run_dir / "stderr.log"
    merged_env = {**os.environ, **(env or {})}
    started = time.perf_counter()
    with stdout_path.open("w", encoding="utf-8", errors="replace") as out_fh, \
         stderr_path.open("w", encoding="utf-8", errors="replace") as err_fh:
        try:
            proc = subprocess.run(
                list(cmd),
                stdout=out_fh,
                stderr=err_fh,
                env=merged_env,
                timeout=timeout,
                check=False,
            )
            code = proc.returncode
        except subprocess.TimeoutExpired:
            out_fh.write(f"\n[harness] timeout after {timeout}s\n")
            code = 124
        except FileNotFoundError as exc:
            err_fh.write(f"[harness] command not found: {exc}\n")
            code = 127
    elapsed = time.perf_counter() - started
    (run_dir / "elapsed.txt").write_text(f"{elapsed:.3f}\n", encoding="utf-8")
    return code


def append_jsonl(path: Path, rows: Iterable[dict]) -> int:
    n = 0
    with path.open("a", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
    return n


def load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    out: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out


def die(msg: str, code: int = 1) -> None:
    print(f"[harness] error: {msg}", file=sys.stderr)
    sys.exit(code)
